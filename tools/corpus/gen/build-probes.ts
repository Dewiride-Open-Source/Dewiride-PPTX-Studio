#!/usr/bin/env node
/**
 * Write the Tier A probe decks, and the manifest that claims them.
 *
 * ```
 * node tools/corpus/gen/build-probes.ts --out corpus/decks --manifest
 * node tools/corpus/gen/build-probes.ts --out <scratch> --id a03-fills
 * node tools/corpus/gen/build-probes.ts --check --out corpus/decks
 * ```
 *
 * `--out` has no default, and that is a rule rather than an oversight:
 * `C008-orphan` fails on any file under `corpus/` that no manifest claims, so
 * a generator that wrote there by accident would break the gate for whoever ran
 * it next. Pointing it at `corpus/decks` is a deliberate act.
 *
 * `--check` rebuilds every deck and compares against what is on disk without
 * writing anything. That is `C-REGEN`: committed bytes and a recipe that
 * reproduces them are two different claims, and only one of them is checked by
 * hashing the file.
 *
 * The manifest is generated rather than hand-written, and everything in it
 * comes from a reviewed source: `description` and `features` are literals in
 * the deck's own module, which is code and is read in review; `sha256` and
 * `bytes` are measured from the file. Nothing is typed twice, and `C017-sorted`
 * holds by construction.
 */

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildProbePackage } from './package.ts';
import { PROBE_DECKS } from './decks/index.ts';
import { outputName, type ProbeDeck } from './types.ts';

const ROOT = resolve(fileURLToPath(import.meta.url), '../../../..');

interface Options {
  readonly out: string;
  readonly only: string | null;
  readonly manifest: boolean;
  readonly check: boolean;
}

function parseArgs(argv: readonly string[]): Options {
  let out = '';
  let only: string | null = null;
  let manifest = false;
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--out') out = argv[++i] ?? '';
    else if (arg === '--id') only = argv[++i] ?? null;
    else if (arg === '--manifest') manifest = true;
    else if (arg === '--check') check = true;
    else throw new Error('unknown argument ' + String(arg));
  }
  if (out === '') {
    throw new Error('--out <dir> is required: this generator defaults nowhere. See the header.');
  }
  return { out, only, manifest, check };
}

const options = parseArgs(process.argv.slice(2));
const outDir = resolve(ROOT, options.out);
const decks =
  options.only === null ? PROBE_DECKS : PROBE_DECKS.filter((d) => d.id === options.only);
if (decks.length === 0) throw new Error('no deck matches --id ' + String(options.only));

interface Built {
  readonly deck: ProbeDeck;
  readonly bytes: Uint8Array;
  readonly sha256: string;
  readonly entries: number;
  readonly slides: number;
}

function build(deck: ProbeDeck): Built {
  const spec = deck.build();
  const { bytes, entries } = buildProbePackage(spec);
  return {
    deck,
    bytes,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    entries,
    slides: spec.slides.length,
  };
}

const built = decks.map(build);

if (options.check) {
  let bad = 0;
  for (const item of built) {
    const path = join(outDir, outputName(item.deck));
    let onDisk: Uint8Array;
    try {
      onDisk = new Uint8Array(readFileSync(path));
    } catch {
      console.error('  MISSING  ' + item.deck.id);
      bad += 1;
      continue;
    }
    const hash = createHash('sha256').update(onDisk).digest('hex');
    if (hash === item.sha256) continue;
    console.error(
      '  DIFFERS  ' + item.deck.id + '\n    on disk ' + hash + '\n    rebuilt ' + item.sha256,
    );
    bad += 1;
  }
  if (bad > 0) {
    console.error('\ncorpus: ' + String(bad) + ' deck(s) do not rebuild to their committed bytes');
    process.exit(1);
  }
  console.log('corpus: ' + String(built.length) + ' deck(s) rebuild byte-for-byte');
  process.exit(0);
}

mkdirSync(outDir, { recursive: true });
for (const item of built) {
  writeFileSync(join(outDir, outputName(item.deck)), item.bytes);
  console.log(
    '  ' +
      item.deck.id.padEnd(16) +
      String(item.bytes.byteLength).padStart(8) +
      ' bytes  ' +
      String(item.entries).padStart(3) +
      ' entries  ' +
      item.sha256.slice(0, 16),
  );
}

if (options.manifest) {
  if (options.only !== null) {
    throw new Error('--manifest writes every entry, so it cannot be combined with --id');
  }
  const manifest = {
    $comment:
      'Tier A of the sub-phase 1.1 corpus: decks this repository generates, committed as bytes ' +
      'and reproducible from the recipe. Generated by tools/corpus/gen/build-probes.ts --manifest; ' +
      'every description and features map is a literal in the deck module it describes.',
    manifestVersion: 1,
    collection: 'decks',
    generatedIn: '1.1',
    adr: 'docs/adr/0009-the-corpus.md',
    generator: 'tools/corpus/gen/build-probes.ts',
    targetCount: 42,
    entries: [...built]
      .sort((a, b) => a.deck.id.localeCompare(b.deck.id))
      .map((item) => ({
        id: item.deck.id,
        kind: 'deck',
        storage: 'committed',
        path: outputName(item.deck),
        license: 'CC0-1.0',
        source: 'self-authored',
        producer: 'tools/corpus/gen',
        sha256: item.sha256,
        bytes: item.bytes.byteLength,
        slides: item.slides,
        zipEntries: item.entries,
        format: item.deck.extension ?? 'pptx',
        features: item.deck.features,
        description: item.deck.description,
        recipe: {
          tool: 'tools/corpus/gen/build-probes.ts',
          args: ['--out', 'corpus/decks', '--id', item.deck.id],
        },
        addedIn: '1.1',
      })),
  };
  const path = join(outDir, 'manifest.json');
  writeFileSync(path, JSON.stringify(manifest, null, 2) + '\n');
  console.log('\nwrote ' + path);
}
